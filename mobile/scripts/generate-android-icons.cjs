// Preserve Phosphor artwork while decoding onboarding icons through expo-image on Android.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const names = ['ArrowUp', 'Bed', 'Bell', 'CalendarDots', 'ChatsTeardrop', 'Export', 'FileText', 'Info', 'User', 'CaretLeft', 'Camera', 'Ticket', 'Check', 'X', 'ClipboardText', 'Envelope', 'LockKey', 'ForkKnife', 'MapPin', 'Van', 'Car', 'Train', 'Bus', 'Boat', 'Anchor', 'Airplane', 'House', 'Clock'];
const weights = ['fill', 'bold', 'regular', 'thin'];
const output = ['// Generated by scripts/generate-android-icons.cjs from phosphor-react-native (MIT).', '// Re-run after upgrading Phosphor. These are the original paths, not replacement artwork.', 'export const androidIconSources = {'];
for (const name of names) {
  const source = fs.readFileSync(path.join(root, 'node_modules/phosphor-react-native/src/defs', name + '.tsx'), 'utf8');
  output.push(`  ${name}: {`);
  for (const weight of weights) {
    const match = source.match(new RegExp("'" + weight + "',\\s*<>([\\s\\S]*?)</>"));
    if (!match) throw new Error(`Missing ${name}/${weight}`);
    const paths = match[1].trim().replace(/<Path\b/g, '<path').replace(/fillRule=/g, 'fill-rule=').replace(/clipRule=/g, 'clip-rule=');
    if (/[{}]/.test(paths) || !paths.startsWith('<path')) throw new Error(`Unsupported SVG markup: ${name}/${weight}`);
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" viewBox="0 0 256 256" fill="#fff">${paths}</svg>`;
    const uri = 'data:image/svg+xml;base64,' + Buffer.from(svg).toString('base64');
    output.push(`    ${weight}: { uri: ${JSON.stringify(uri)} },`);
  }
  output.push('  },');
}
output.push('} as const;', '');
fs.writeFileSync(path.join(root, 'components/ui/androidIconSources.ts'), output.join('\n'));
console.log(`Generated ${names.length * weights.length} bundled icon variants.`);
